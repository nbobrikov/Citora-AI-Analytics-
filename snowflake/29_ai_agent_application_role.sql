-- Run once as ACCOUNTADMIN after the website RBAC tables have been created.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

ALTER TABLE CITORA.PLATFORM.APP_USER_ROLES
    DROP CONSTRAINT CK_APP_USER_ROLES_CODE;
ALTER TABLE CITORA.PLATFORM.APP_USER_ROLES
    ADD CONSTRAINT CK_APP_USER_ROLES_CODE
    CHECK (ROLE_CODE IN ('REPORTER', 'DICTIONARY', 'DATA_LOADER', 'AI_AGENT', 'ADMIN'));

