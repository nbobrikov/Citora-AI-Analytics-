-- Add the separately assignable AI Agent application role.
-- Run once as ACCOUNTADMIN after the website RBAC tables have been created.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

EXECUTE IMMEDIATE $$
BEGIN
    ALTER TABLE CITORA.PLATFORM.APP_USER_ROLES
        DROP CONSTRAINT CK_APP_USER_ROLES_CODE;
EXCEPTION
    WHEN STATEMENT_ERROR THEN NULL;
END;
$$;
ALTER TABLE CITORA.PLATFORM.APP_USER_ROLES
    ADD CONSTRAINT CK_APP_USER_ROLES_CODE
    CHECK (ROLE_CODE IN ('REPORTER', 'DICTIONARY', 'DATA_LOADER', 'AI_AGENT', 'ADMIN'))
    ENABLE NOVALIDATE;

EXECUTE IMMEDIATE $$
BEGIN
    ALTER TABLE CITORA.PLATFORM.APP_INVITATION_ROLES
        DROP CONSTRAINT CK_APP_INVITATION_ROLES_CODE;
EXCEPTION
    WHEN STATEMENT_ERROR THEN NULL;
END;
$$;
ALTER TABLE CITORA.PLATFORM.APP_INVITATION_ROLES
    ADD CONSTRAINT CK_APP_INVITATION_ROLES_CODE
    CHECK (ROLE_CODE IN ('REPORTER', 'DICTIONARY', 'DATA_LOADER', 'AI_AGENT', 'ADMIN'))
    ENABLE NOVALIDATE;

