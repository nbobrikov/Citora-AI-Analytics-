-- Citora dbt infrastructure and least-privilege access.
-- Run once after RAW loading works and before registering the dbt project.

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS CITORA_TRANSFORMER
    COMMENT = 'Reads Citora RAW data and builds dbt models';

GRANT ROLE CITORA_TRANSFORMER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS CITORA_TRANSFORMING_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Warehouse for Citora dbt transformations';

CREATE SCHEMA IF NOT EXISTS CITORA.CONFIG
    COMMENT = 'Versioned dbt seed dictionaries';

CREATE SCHEMA IF NOT EXISTS CITORA.STAGING
    COMMENT = 'Normalized dbt source models';

CREATE SCHEMA IF NOT EXISTS CITORA.INTERMEDIATE
    COMMENT = 'Intermediate Citora business transformations';

-- ANALYTICS and PLATFORM are created by 01_infrastructure.sql.

USE ROLE SECURITYADMIN;

GRANT USAGE ON WAREHOUSE CITORA_TRANSFORMING_WH
    TO ROLE CITORA_TRANSFORMER;

GRANT USAGE ON DATABASE CITORA
    TO ROLE CITORA_TRANSFORMER;

GRANT USAGE ON SCHEMA CITORA.RAW
    TO ROLE CITORA_TRANSFORMER;

GRANT SELECT ON ALL TABLES IN SCHEMA CITORA.RAW
    TO ROLE CITORA_TRANSFORMER;

GRANT SELECT ON FUTURE TABLES IN SCHEMA CITORA.RAW
    TO ROLE CITORA_TRANSFORMER;

GRANT SELECT ON ALL VIEWS IN SCHEMA CITORA.RAW
    TO ROLE CITORA_TRANSFORMER;

GRANT SELECT ON FUTURE VIEWS IN SCHEMA CITORA.RAW
    TO ROLE CITORA_TRANSFORMER;

GRANT USAGE ON SCHEMA CITORA.PLATFORM
    TO ROLE CITORA_TRANSFORMER;

GRANT READ ON GIT REPOSITORY CITORA.PLATFORM.CITORA_REPO
    TO ROLE CITORA_TRANSFORMER;

GRANT CREATE DBT PROJECT ON SCHEMA CITORA.PLATFORM
    TO ROLE CITORA_TRANSFORMER;

GRANT USAGE ON SCHEMA CITORA.CONFIG
    TO ROLE CITORA_TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA CITORA.CONFIG
    TO ROLE CITORA_TRANSFORMER;

GRANT USAGE ON SCHEMA CITORA.STAGING
    TO ROLE CITORA_TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA CITORA.STAGING
    TO ROLE CITORA_TRANSFORMER;

GRANT USAGE ON SCHEMA CITORA.INTERMEDIATE
    TO ROLE CITORA_TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA CITORA.INTERMEDIATE
    TO ROLE CITORA_TRANSFORMER;

GRANT USAGE ON SCHEMA CITORA.ANALYTICS
    TO ROLE CITORA_TRANSFORMER;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA CITORA.ANALYTICS
    TO ROLE CITORA_TRANSFORMER;

-- Verification: every statement above is idempotent and safe to re-run.
USE ROLE CITORA_TRANSFORMER;
USE WAREHOUSE CITORA_TRANSFORMING_WH;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

SELECT CURRENT_ROLE() AS active_role,
       CURRENT_WAREHOUSE() AS active_warehouse,
       CURRENT_DATABASE() AS active_database,
       CURRENT_SCHEMA() AS active_schema;

SELECT COUNT(*) AS successful_raw_loads
FROM CITORA.RAW.LOAD_HISTORY
WHERE STATUS = 'SUCCESS';

SHOW DBT PROJECTS IN SCHEMA CITORA.PLATFORM;
