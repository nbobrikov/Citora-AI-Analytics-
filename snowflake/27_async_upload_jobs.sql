-- Durable status registry for website uploads executed asynchronously in Snowflake.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

CREATE TABLE IF NOT EXISTS CITORA.PLATFORM.UPLOAD_JOBS (
    JOB_ID VARCHAR NOT NULL,
    LOAD_ID VARCHAR,
    SOURCE_FILE VARCHAR NOT NULL,
    FILE_SIZE NUMBER NOT NULL,
    UPLOADED_BY VARCHAR NOT NULL,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    STATUS VARCHAR NOT NULL,
    RAW_STATEMENT_HANDLE VARCHAR,
    DBT_STATEMENT_HANDLE VARCHAR,
    ERROR_MESSAGE VARCHAR,
    CONSTRAINT PK_UPLOAD_JOBS PRIMARY KEY (JOB_ID),
    CONSTRAINT CK_UPLOAD_JOB_STATUS CHECK (
        STATUS IN ('SUBMITTED', 'RAW_RUNNING', 'PREPARING', 'DBT_RUNNING', 'SUCCESS', 'FAILED')
    )
);

GRANT SELECT, INSERT, UPDATE, DELETE
ON TABLE CITORA.PLATFORM.UPLOAD_JOBS
TO ROLE CITORA_FRONTEND_UPLOADER;

