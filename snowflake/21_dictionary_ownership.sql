-- Add explicit dictionary authorship and validate per-owner names.
-- OWNER_EMAIL identifies whose reports may use the dictionary.
-- CREATED_BY records who originally created or imported it.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA CONFIG;

ALTER TABLE CITORA.CONFIG.DICTIONARY_SETS
    ADD COLUMN IF NOT EXISTS CREATED_BY VARCHAR;

ALTER TABLE CITORA.CONFIG.DICTIONARY_SETS
    ADD COLUMN IF NOT EXISTS VISIBILITY VARCHAR DEFAULT 'PRIVATE';

UPDATE CITORA.CONFIG.DICTIONARY_SETS
SET CREATED_BY = OWNER_EMAIL,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHERE CREATED_BY IS NULL
  AND OWNER_EMAIL IS NOT NULL;

UPDATE CITORA.CONFIG.DICTIONARY_SETS
SET VISIBILITY = 'PRIVATE',
    UPDATED_AT = CURRENT_TIMESTAMP()
WHERE VISIBILITY IS NULL
   OR UPPER(VISIBILITY) NOT IN ('PRIVATE', 'PUBLIC');

DROP PROCEDURE IF EXISTS CITORA.CONFIG.CREATE_DICTIONARY(VARCHAR, VARCHAR, VARCHAR, VARCHAR);

CREATE OR REPLACE PROCEDURE CITORA.CONFIG.CREATE_DICTIONARY(
    OWNER_EMAIL VARCHAR,
    DICTIONARY_NAME VARCHAR,
    CREATED_BY VARCHAR,
    DESCRIPTION VARCHAR,
    VISIBILITY VARCHAR
)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    NEW_DICTIONARY_ID VARCHAR DEFAULT UUID_STRING();
    EXISTING_COUNT NUMBER DEFAULT 0;
BEGIN
    IF (NULLIF(TRIM(OWNER_EMAIL), '') IS NULL
        OR NULLIF(TRIM(DICTIONARY_NAME), '') IS NULL
        OR NULLIF(TRIM(CREATED_BY), '') IS NULL
        OR UPPER(TRIM(VISIBILITY)) NOT IN ('PRIVATE', 'PUBLIC')) THEN
        RETURN OBJECT_CONSTRUCT(
            'status', 'invalid',
            'message', 'OWNER_EMAIL, DICTIONARY_NAME, CREATED_BY and valid VISIBILITY are required'
        );
    END IF;

    SELECT COUNT(*)
    INTO :EXISTING_COUNT
    FROM CITORA.CONFIG.DICTIONARY_SETS
    WHERE LOWER(OWNER_EMAIL) = LOWER(:OWNER_EMAIL)
      AND LOWER(TRIM(DICTIONARY_NAME)) = LOWER(TRIM(:DICTIONARY_NAME));

    IF (EXISTING_COUNT > 0) THEN
        RETURN OBJECT_CONSTRUCT(
            'status', 'duplicate_name',
            'message', 'Dictionary name must be unique for this owner'
        );
    END IF;

    INSERT INTO CITORA.CONFIG.DICTIONARY_SETS (
        DICTIONARY_ID,
        OWNER_EMAIL,
        DICTIONARY_NAME,
        CREATED_BY,
        VISIBILITY,
        DESCRIPTION,
        IS_DEFAULT
    ) VALUES (
        :NEW_DICTIONARY_ID,
        LOWER(TRIM(:OWNER_EMAIL)),
        TRIM(:DICTIONARY_NAME),
        LOWER(TRIM(:CREATED_BY)),
        UPPER(TRIM(:VISIBILITY)),
        :DESCRIPTION,
        FALSE
    );

    RETURN OBJECT_CONSTRUCT(
        'status', 'created',
        'dictionary_id', NEW_DICTIONARY_ID
    );
END;
$$;

-- Snowflake standard-table UNIQUE constraints are informational, so duplicate
-- names are validated explicitly before any create/rename operation.
CREATE OR REPLACE VIEW CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS AS
SELECT
    LOWER(OWNER_EMAIL) AS OWNER_EMAIL,
    LOWER(TRIM(DICTIONARY_NAME)) AS NORMALIZED_DICTIONARY_NAME,
    COUNT(*) AS DICTIONARY_COUNT
FROM CITORA.CONFIG.DICTIONARY_SETS
WHERE OWNER_EMAIL IS NOT NULL
GROUP BY LOWER(OWNER_EMAIL), LOWER(TRIM(DICTIONARY_NAME))
HAVING COUNT(*) > 1;

GRANT SELECT ON VIEW CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS
    TO ROLE CITORA_FRONTEND_READER;
GRANT SELECT ON VIEW CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS
    TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON PROCEDURE CITORA.CONFIG.CREATE_DICTIONARY(VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR)
    TO ROLE CITORA_FRONTEND_UPLOADER;

SELECT
    DICTIONARY_ID,
    OWNER_EMAIL,
    DICTIONARY_NAME,
    CREATED_BY,
    VISIBILITY,
    IS_DEFAULT,
    CREATED_AT
FROM CITORA.CONFIG.DICTIONARY_SETS
ORDER BY OWNER_EMAIL, DICTIONARY_NAME;

SELECT *
FROM CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS;
