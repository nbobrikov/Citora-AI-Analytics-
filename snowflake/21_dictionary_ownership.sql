-- Add explicit dictionary authorship and validate per-owner names.
-- OWNER_EMAIL identifies whose reports may use the dictionary.
-- CREATED_BY records who originally created or imported it.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA CONFIG;

ALTER TABLE CITORA.CONFIG.DICTIONARY_SETS
    ADD COLUMN IF NOT EXISTS CREATED_BY VARCHAR;

UPDATE CITORA.CONFIG.DICTIONARY_SETS
SET CREATED_BY = OWNER_EMAIL,
    UPDATED_AT = CURRENT_TIMESTAMP()
WHERE CREATED_BY IS NULL
  AND OWNER_EMAIL IS NOT NULL;

-- Snowflake standard-table UNIQUE constraints are informational, so duplicate
-- names are validated explicitly before any create/rename operation.
CREATE OR REPLACE VIEW CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS AS
SELECT
    LOWER(OWNER_EMAIL) AS OWNER_EMAIL,
    LOWER(TRIM(DICTIONARY_NAME)) AS NORMALIZED_DICTIONARY_NAME,
    COUNT(*) AS DICTIONARY_COUNT
FROM CITORA.CONFIG.DICTIONARY_SETS
WHERE OWNER_EMAIL IS NOT NULL
GROUP BY LOWER(OWNER_EMAIL), LOWER(TRIM(DICTIONARY_NAME))
HAVING COUNT(*) > 1;

GRANT SELECT ON VIEW CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS
    TO ROLE CITORA_FRONTEND_READER;
GRANT SELECT ON VIEW CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS
    TO ROLE CITORA_FRONTEND_UPLOADER;

SELECT
    DICTIONARY_ID,
    OWNER_EMAIL,
    DICTIONARY_NAME,
    CREATED_BY,
    IS_DEFAULT,
    CREATED_AT
FROM CITORA.CONFIG.DICTIONARY_SETS
ORDER BY OWNER_EMAIL, DICTIONARY_NAME;

SELECT *
FROM CITORA.CONFIG.V_DICTIONARY_NAME_CONFLICTS;
