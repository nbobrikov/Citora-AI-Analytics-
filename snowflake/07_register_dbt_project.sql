-- Register the versioned dbt project directly from the Snowflake Git clone.
-- Run after 06_dbt_infrastructure.sql.

USE ROLE CITORA_TRANSFORMER;
USE WAREHOUSE CITORA_TRANSFORMING_WH;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

CREATE DBT PROJECT IF NOT EXISTS CITORA.PLATFORM.CITORA_DBT_PROJECT
    FROM '@CITORA.PLATFORM.CITORA_REPO/branches/main/dbt'
    DEFAULT_TARGET = 'prod'
    AUTO_COMPILE = TRUE
    COMMENT = 'Citora analytics transformations deployed from GitHub';

SHOW DBT PROJECTS LIKE 'CITORA_DBT_PROJECT'
    IN SCHEMA CITORA.PLATFORM;

DESCRIBE DBT PROJECT CITORA.PLATFORM.CITORA_DBT_PROJECT;
