-- User-owned dictionaries for report-time attribution.
-- Run as ACCOUNTADMIN after dbt seeds have been loaded.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;

CREATE TABLE IF NOT EXISTS CITORA.CONFIG.DICTIONARY_SETS (
    DICTIONARY_ID VARCHAR NOT NULL DEFAULT UUID_STRING(),
    OWNER_EMAIL VARCHAR,
    DICTIONARY_NAME VARCHAR NOT NULL,
    CREATED_BY VARCHAR,
    DESCRIPTION VARCHAR,
    IS_DEFAULT BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_DICTIONARY_SETS PRIMARY KEY (DICTIONARY_ID)
);

CREATE TABLE IF NOT EXISTS CITORA.CONFIG.DICTIONARY_ENTRIES (
    DICTIONARY_ID VARCHAR NOT NULL,
    MAPPING_TYPE VARCHAR NOT NULL,
    PRIORITY NUMBER NOT NULL,
    MATCH_VALUE VARCHAR NOT NULL,
    OUTPUT_SOURCE VARCHAR,
    OUTPUT_SEGMENT VARCHAR,
    OUTPUT_MANAGER VARCHAR,
    IS_PREFIX BOOLEAN NOT NULL DEFAULT FALSE,
    CREATED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- The existing seed-based dictionary starts unclaimed. The first authenticated
-- Citora user opening Dictionaries claims it with their e-mail address.
SET LEGACY_DICTIONARY_ID = 'citora-legacy-default-v1';

INSERT INTO CITORA.CONFIG.DICTIONARY_SETS (
    DICTIONARY_ID, OWNER_EMAIL, DICTIONARY_NAME, CREATED_BY, DESCRIPTION, IS_DEFAULT
)
SELECT
    $LEGACY_DICTIONARY_ID,
    NULL,
    'Основной справочник',
    NULL,
    'Текущий справочник, перенесённый из исходной конфигурации Citora',
    TRUE
WHERE NOT EXISTS (
    SELECT 1
    FROM CITORA.CONFIG.DICTIONARY_SETS
);

INSERT INTO CITORA.CONFIG.DICTIONARY_ENTRIES
    (DICTIONARY_ID, MAPPING_TYPE, PRIORITY, MATCH_VALUE, OUTPUT_SOURCE, OUTPUT_SEGMENT, OUTPUT_MANAGER, IS_PREFIX)
SELECT $LEGACY_DICTIONARY_ID, 'SOURCE', PRIORITY,
       LOWER(TRIM(UTM_SOURCE)), SOURCE, NULL, NULL, ENDSWITH(TRIM(UTM_SOURCE), '*')
FROM CITORA.CONFIG.UTM_SOURCE_MAPPING
WHERE NOT EXISTS (SELECT 1 FROM CITORA.CONFIG.DICTIONARY_ENTRIES)
UNION ALL
SELECT $LEGACY_DICTIONARY_ID, 'SEGMENT', PRIORITY,
       LOWER(TRIM(UTM_CONTENT)), NULL, SEGMENT, NULL, ENDSWITH(TRIM(UTM_CONTENT), '*')
FROM CITORA.CONFIG.UTM_CONTENT_MAPPING
WHERE NOT EXISTS (SELECT 1 FROM CITORA.CONFIG.DICTIONARY_ENTRIES)
UNION ALL
SELECT $LEGACY_DICTIONARY_ID, 'PROMO', PRIORITY,
       LOWER(TRIM(PROMOCODE)), SOURCE, SEGMENT, NULL, FALSE
FROM CITORA.CONFIG.PROMOCODE_MAPPING
WHERE NOT EXISTS (SELECT 1 FROM CITORA.CONFIG.DICTIONARY_ENTRIES)
UNION ALL
SELECT $LEGACY_DICTIONARY_ID, 'MANAGER', ROW_NUMBER() OVER (ORDER BY MANAGER),
       LOWER(TRIM(MANAGER)), NULL, NULL, MANAGER, FALSE
FROM CITORA.CONFIG.ALLOWED_MANAGERS
WHERE NOT EXISTS (SELECT 1 FROM CITORA.CONFIG.DICTIONARY_ENTRIES);

GRANT USAGE ON SCHEMA CITORA.CONFIG TO ROLE CITORA_FRONTEND_READER;
GRANT SELECT, UPDATE ON TABLE CITORA.CONFIG.DICTIONARY_SETS TO ROLE CITORA_FRONTEND_READER;
GRANT SELECT ON TABLE CITORA.CONFIG.DICTIONARY_ENTRIES TO ROLE CITORA_FRONTEND_READER;

GRANT USAGE ON SCHEMA CITORA.CONFIG TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.CONFIG.DICTIONARY_SETS TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.CONFIG.DICTIONARY_ENTRIES TO ROLE CITORA_FRONTEND_UPLOADER;

SELECT DICTIONARY_ID, OWNER_EMAIL, DICTIONARY_NAME, CREATED_BY, IS_DEFAULT, CREATED_AT
FROM CITORA.CONFIG.DICTIONARY_SETS
ORDER BY CREATED_AT;
