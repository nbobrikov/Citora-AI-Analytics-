-- Build all Citora dbt models for the full available RAW history.
-- Run after 08_run_dbt_seeds.sql succeeds.

USE ROLE CITORA_TRANSFORMER;
USE WAREHOUSE CITORA_TRANSFORMING_WH;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

EXECUTE DBT PROJECT CITORA.PLATFORM.CITORA_DBT_PROJECT
    ARGS = 'run --target prod --full-refresh';

-- Verify the main layer row counts without exposing contact-level data.
SELECT 'STG_CRM_DEALS' AS model, COUNT(*) AS row_count
FROM CITORA.STAGING.STG_CRM_DEALS
UNION ALL
SELECT 'INT_CRM_DEALS_PREPARED' AS model, COUNT(*) AS row_count
FROM CITORA.INTERMEDIATE.INT_CRM_DEALS_PREPARED
UNION ALL
SELECT 'INT_CRM_APPLICATIONS' AS model, COUNT(*) AS row_count
FROM CITORA.INTERMEDIATE.INT_CRM_APPLICATIONS
UNION ALL
SELECT 'INT_CRM_SALES' AS model, COUNT(*) AS row_count
FROM CITORA.INTERMEDIATE.INT_CRM_SALES
UNION ALL
SELECT 'INT_APPLICATION_SALES_MATCHES' AS model, COUNT(*) AS row_count
FROM CITORA.INTERMEDIATE.INT_APPLICATION_SALES_MATCHES
UNION ALL
SELECT 'INT_APPLICATION_SALES_ENRICHED' AS model, COUNT(*) AS row_count
FROM CITORA.INTERMEDIATE.INT_APPLICATION_SALES_ENRICHED
ORDER BY model;

SELECT
    match_type,
    COUNT(*) AS row_count,
    COUNT(DISTINCT application_id) AS application_count,
    COUNT(DISTINCT sale_id) AS sale_count,
    SUM(amount) AS total_amount
FROM CITORA.INTERMEDIATE.INT_APPLICATION_SALES_ENRICHED
GROUP BY match_type
ORDER BY match_type;
