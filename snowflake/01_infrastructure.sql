-- Citora AI Analytic: base Snowflake infrastructure.
-- Run once with a role that can create roles, warehouses, databases, and schemas.

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS CITORA_LOADER
    COMMENT = 'Loads validated Excel data into the Citora RAW layer';

GRANT ROLE CITORA_LOADER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS CITORA_LOADING_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Warehouse for Citora Excel ingestion';

CREATE DATABASE IF NOT EXISTS CITORA
    COMMENT = 'Citora analytics platform';

CREATE SCHEMA IF NOT EXISTS CITORA.RAW
    COMMENT = 'Source data loaded from Excel without business transformations';

CREATE SCHEMA IF NOT EXISTS CITORA.ANALYTICS
    COMMENT = 'Analytics-ready models produced by dbt';

CREATE SCHEMA IF NOT EXISTS CITORA.PLATFORM
    COMMENT = 'Stages, procedures, and operational objects';

CREATE STAGE IF NOT EXISTS CITORA.PLATFORM.CITORA_RAW_STAGE
    ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Excel files and their YAML contracts';

GRANT USAGE ON WAREHOUSE CITORA_LOADING_WH TO ROLE CITORA_LOADER;
GRANT USAGE ON DATABASE CITORA TO ROLE CITORA_LOADER;
GRANT USAGE ON SCHEMA CITORA.RAW TO ROLE CITORA_LOADER;
GRANT USAGE ON SCHEMA CITORA.PLATFORM TO ROLE CITORA_LOADER;

GRANT CREATE TABLE ON SCHEMA CITORA.RAW TO ROLE CITORA_LOADER;
GRANT CREATE PROCEDURE ON SCHEMA CITORA.PLATFORM TO ROLE CITORA_LOADER;
GRANT CREATE TASK ON SCHEMA CITORA.PLATFORM TO ROLE CITORA_LOADER;

GRANT READ, WRITE ON STAGE CITORA.PLATFORM.CITORA_RAW_STAGE
    TO ROLE CITORA_LOADER;

-- Existing tables and procedures keep their ownership. Future RAW tables are
-- created by CITORA_LOADER and therefore owned by that role.

USE ROLE CITORA_LOADER;
USE WAREHOUSE CITORA_LOADING_WH;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

SHOW STAGES IN SCHEMA CITORA.PLATFORM;
