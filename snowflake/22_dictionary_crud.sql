-- Dictionary row identifiers and grants for website CRUD operations.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA CONFIG;

ALTER TABLE CITORA.CONFIG.DICTIONARY_ENTRIES
    ADD COLUMN IF NOT EXISTS ENTRY_ID VARCHAR;

UPDATE CITORA.CONFIG.DICTIONARY_ENTRIES
SET ENTRY_ID = UUID_STRING()
WHERE ENTRY_ID IS NULL;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.CONFIG.DICTIONARY_SETS
    TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.CONFIG.DICTIONARY_ENTRIES
    TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON PROCEDURE CITORA.CONFIG.CREATE_DICTIONARY(VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR)
    TO ROLE CITORA_FRONTEND_UPLOADER;

SELECT
    COUNT(*) AS ENTRY_COUNT,
    COUNT(DISTINCT ENTRY_ID) AS DISTINCT_ENTRY_ID_COUNT,
    COUNT_IF(ENTRY_ID IS NULL) AS MISSING_ENTRY_ID_COUNT
FROM CITORA.CONFIG.DICTIONARY_ENTRIES;
