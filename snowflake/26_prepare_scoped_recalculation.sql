-- Remove the existing analytical rows for one queued scope before dbt rebuilds it.
-- The explicit procedure makes scoped recalculation independent of dbt hook rendering.

USE ROLE CITORA_TRANSFORMER;
USE WAREHOUSE CITORA_TRANSFORMING_WH;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

CREATE OR REPLACE PROCEDURE CITORA.PLATFORM.PREPARE_SCOPED_RECALCULATION(
    P_RECALCULATION_ID VARCHAR
)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_SCOPE_ROWS NUMBER DEFAULT 0;
    V_REPORTING_ROWS NUMBER DEFAULT 0;
    V_FACT_ROWS NUMBER DEFAULT 0;
BEGIN
    SELECT COUNT(*)
      INTO :V_SCOPE_ROWS
      FROM CITORA.PLATFORM.RECALCULATION_IDENTIFIERS
     WHERE RECALCULATION_ID = :P_RECALCULATION_ID;

    IF (V_SCOPE_ROWS = 0) THEN
        RETURN OBJECT_CONSTRUCT(
            'status', 'empty_scope',
            'recalculation_id', P_RECALCULATION_ID,
            'reporting_rows_deleted', 0,
            'fact_rows_deleted', 0
        );
    END IF;

    DELETE FROM CITORA.ANALYTICS.FCT_REPORTING_METRICS AS TARGET
     WHERE EXISTS (
        SELECT 1
          FROM CITORA.PLATFORM.RECALCULATION_IDENTIFIERS AS SCOPE
         WHERE SCOPE.RECALCULATION_ID = :P_RECALCULATION_ID
           AND (
               LOWER(TRIM(SCOPE.PHONE_NUMBER_HASH)) = LOWER(TRIM(TARGET.PHONE_NUMBER))
               OR LOWER(TRIM(SCOPE.CONTACT_ID_HASH)) = LOWER(TRIM(TARGET.APPLICATION_CONTACT_ID))
               OR LOWER(TRIM(SCOPE.CONTACT_ID_HASH)) = LOWER(TRIM(TARGET.SALE_CONTACT_ID))
           )
     );
    V_REPORTING_ROWS := SQLROWCOUNT;

    DELETE FROM CITORA.ANALYTICS.FCT_APPLICATION_SALES AS TARGET
     WHERE EXISTS (
        SELECT 1
          FROM CITORA.PLATFORM.RECALCULATION_IDENTIFIERS AS SCOPE
         WHERE SCOPE.RECALCULATION_ID = :P_RECALCULATION_ID
           AND (
               LOWER(TRIM(SCOPE.PHONE_NUMBER_HASH)) = LOWER(TRIM(TARGET.PHONE_NUMBER))
               OR LOWER(TRIM(SCOPE.CONTACT_ID_HASH)) = LOWER(TRIM(TARGET.APPLICATION_CONTACT_ID))
               OR LOWER(TRIM(SCOPE.CONTACT_ID_HASH)) = LOWER(TRIM(TARGET.SALE_CONTACT_ID))
           )
     );
    V_FACT_ROWS := SQLROWCOUNT;

    UPDATE CITORA.PLATFORM.RECALCULATION_QUEUE
       SET STATUS = 'PENDING',
           DBT_STATEMENT_HANDLE = NULL,
           STARTED_AT = NULL,
           FINISHED_AT = NULL,
           ERROR_MESSAGE = NULL
     WHERE RECALCULATION_ID = :P_RECALCULATION_ID;

    RETURN OBJECT_CONSTRUCT(
        'status', 'prepared',
        'recalculation_id', P_RECALCULATION_ID,
        'scope_rows', V_SCOPE_ROWS,
        'reporting_rows_deleted', V_REPORTING_ROWS,
        'fact_rows_deleted', V_FACT_ROWS
    );
END;
$$;

GRANT USAGE ON PROCEDURE CITORA.PLATFORM.PREPARE_SCOPED_RECALCULATION(VARCHAR)
    TO ROLE CITORA_FRONTEND_UPLOADER;

DESCRIBE PROCEDURE CITORA.PLATFORM.PREPARE_SCOPED_RECALCULATION(VARCHAR);
