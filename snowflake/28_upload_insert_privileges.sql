-- Restore the privileges required by the owner-rights Excel loader procedure.
-- Safe to run repeatedly as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;

GRANT USAGE ON DATABASE CITORA TO ROLE CITORA_LOADER;
GRANT USAGE ON SCHEMA CITORA.RAW TO ROLE CITORA_LOADER;
GRANT USAGE ON SCHEMA CITORA.PLATFORM TO ROLE CITORA_LOADER;

GRANT SELECT, INSERT ON TABLE CITORA.RAW.CRM_DEALS
    TO ROLE CITORA_LOADER;
GRANT SELECT, INSERT, UPDATE ON TABLE CITORA.RAW.LOAD_HISTORY
    TO ROLE CITORA_LOADER;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE CITORA.PLATFORM.RECALCULATION_QUEUE
    TO ROLE CITORA_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE CITORA.PLATFORM.RECALCULATION_IDENTIFIERS
    TO ROLE CITORA_LOADER;

SHOW GRANTS TO ROLE CITORA_LOADER;
