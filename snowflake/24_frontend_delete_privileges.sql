-- Repair privileges for DELETE_UPLOAD when its current owner is the frontend role.
-- Safe to run repeatedly as ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA RAW;

GRANT USAGE ON DATABASE CITORA TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON SCHEMA CITORA.RAW TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT, DELETE ON TABLE CITORA.RAW.CRM_DEALS
    TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT, DELETE ON TABLE CITORA.RAW.LOAD_HISTORY
    TO ROLE CITORA_FRONTEND_UPLOADER;

SHOW GRANTS TO ROLE CITORA_FRONTEND_UPLOADER;
