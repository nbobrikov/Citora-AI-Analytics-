-- Queue the exact RAW scope that must be recalculated by dbt.
-- Run once as ACCOUNTADMIN, then re-register upload and delete procedures.

USE ROLE ACCOUNTADMIN;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

CREATE TABLE IF NOT EXISTS CITORA.PLATFORM.RECALCULATION_QUEUE (
    RECALCULATION_ID VARCHAR NOT NULL,
    OPERATION_TYPE VARCHAR NOT NULL,
    LOAD_ID VARCHAR NOT NULL,
    REQUESTED_AT TIMESTAMP_TZ NOT NULL,
    REQUESTED_BY VARCHAR NOT NULL,
    DATE_FROM DATE,
    DATE_TO DATE,
    CONVERSION_PERIOD_DAYS NUMBER(5, 0) NOT NULL DEFAULT 30,
    STATUS VARCHAR NOT NULL DEFAULT 'PENDING',
    DBT_STATEMENT_HANDLE VARCHAR,
    STARTED_AT TIMESTAMP_TZ,
    FINISHED_AT TIMESTAMP_TZ,
    ERROR_MESSAGE VARCHAR,
    CONSTRAINT PK_RECALCULATION_QUEUE PRIMARY KEY (RECALCULATION_ID),
    CONSTRAINT CK_RECALCULATION_OPERATION CHECK (OPERATION_TYPE IN ('LOAD', 'DELETE')),
    CONSTRAINT CK_RECALCULATION_STATUS CHECK (STATUS IN ('PENDING', 'RUNNING', 'SUCCESS', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS CITORA.PLATFORM.RECALCULATION_IDENTIFIERS (
    RECALCULATION_ID VARCHAR NOT NULL,
    PHONE_NUMBER_HASH VARCHAR,
    CONTACT_ID_HASH VARCHAR,
    CREATED_AT TIMESTAMP_TZ NOT NULL
);

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.PLATFORM.RECALCULATION_QUEUE
    TO ROLE CITORA_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.PLATFORM.RECALCULATION_IDENTIFIERS
    TO ROLE CITORA_LOADER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.PLATFORM.RECALCULATION_QUEUE
    TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CITORA.PLATFORM.RECALCULATION_IDENTIFIERS
    TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT ON TABLE CITORA.PLATFORM.RECALCULATION_QUEUE
    TO ROLE CITORA_TRANSFORMER;
GRANT SELECT ON TABLE CITORA.PLATFORM.RECALCULATION_IDENTIFIERS
    TO ROLE CITORA_TRANSFORMER;

SHOW GRANTS ON TABLE CITORA.PLATFORM.RECALCULATION_QUEUE;
SHOW GRANTS ON TABLE CITORA.PLATFORM.RECALCULATION_IDENTIFIERS;
