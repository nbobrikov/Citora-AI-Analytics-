-- Enable the Citora website upload workflow.
-- Run once as ACCOUNTADMIN after fetching the latest Git branch.

USE ROLE ACCOUNTADMIN;

ALTER TABLE CITORA.RAW.LOAD_HISTORY ADD COLUMN IF NOT EXISTS UPLOADED_BY VARCHAR;
ALTER TABLE CITORA.RAW.LOAD_HISTORY ADD COLUMN IF NOT EXISTS DATA_PERIOD_START DATE;
ALTER TABLE CITORA.RAW.LOAD_HISTORY ADD COLUMN IF NOT EXISTS DATA_PERIOD_END DATE;
ALTER TABLE CITORA.RAW.LOAD_HISTORY ADD COLUMN IF NOT EXISTS DBT_STATUS VARCHAR;
ALTER TABLE CITORA.RAW.LOAD_HISTORY ADD COLUMN IF NOT EXISTS DBT_FINISHED_AT TIMESTAMP_TZ;

EXECUTE IMMEDIATE FROM
    @CITORA.PLATFORM.CITORA_REPO/branches/main/snowflake/03_register_procedure.sql;

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS CITORA_FRONTEND_UPLOADER
    COMMENT = 'Restricted upload and dbt execution role used by the Citora website';

GRANT ROLE CITORA_FRONTEND_UPLOADER TO ROLE SYSADMIN;
GRANT ROLE CITORA_TRANSFORMER TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT ROLE CITORA_FRONTEND_UPLOADER TO USER CITORA_FRONTEND_SERVICE;

USE ROLE ACCOUNTADMIN;

GRANT USAGE ON WAREHOUSE CITORA_LOADING_WH TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON WAREHOUSE CITORA_TRANSFORMING_WH TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON DATABASE CITORA TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON SCHEMA CITORA.PLATFORM TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON SCHEMA CITORA.RAW TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON SCHEMA CITORA.ANALYTICS TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT READ, WRITE ON STAGE CITORA.PLATFORM.CITORA_RAW_STAGE TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON PROCEDURE CITORA.PLATFORM.LOAD_EXCEL(VARCHAR, VARCHAR, VARCHAR, VARCHAR, VARCHAR)
    TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT USAGE ON DBT PROJECT CITORA.PLATFORM.CITORA_DBT_PROJECT TO ROLE CITORA_FRONTEND_UPLOADER;
GRANT SELECT, UPDATE ON TABLE CITORA.RAW.LOAD_HISTORY TO ROLE CITORA_FRONTEND_UPLOADER;

SHOW GRANTS TO ROLE CITORA_FRONTEND_UPLOADER;
