-- Prepare the append-only RAW load journal.
-- Before the first historical load, remove the old CRM_DEALS table manually.

USE ROLE CITORA_LOADER;
USE WAREHOUSE CITORA_LOADING_WH;
USE DATABASE CITORA;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS CITORA.RAW.LOAD_HISTORY (
    LOAD_ID VARCHAR NOT NULL,
    SOURCE_FILE VARCHAR NOT NULL,
    FILE_HASH VARCHAR,
    STARTED_AT TIMESTAMP_TZ NOT NULL,
    FINISHED_AT TIMESTAMP_TZ,
    STATUS VARCHAR NOT NULL,
    ROWS_LOADED NUMBER,
    ERROR_MESSAGE VARCHAR
)
COMMENT = 'One row per successfully loaded Excel file';
