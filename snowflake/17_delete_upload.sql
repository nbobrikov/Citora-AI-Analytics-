-- Delete one immutable RAW batch and expose the operation only through a procedure.
-- Run once as ACCOUNTADMIN after 16_frontend_uploads.sql.

USE ROLE CITORA_LOADER;
USE WAREHOUSE CITORA_LOADING_WH;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

-- DELETE_UPLOAD executes with owner's rights. Keep the procedure owner able to
-- read and delete both the immutable RAW batch and its load-history record.
GRANT SELECT, DELETE ON TABLE CITORA.RAW.CRM_DEALS TO ROLE CITORA_LOADER;
GRANT SELECT, DELETE ON TABLE CITORA.RAW.LOAD_HISTORY TO ROLE CITORA_LOADER;

CREATE OR REPLACE PROCEDURE CITORA.PLATFORM.DELETE_UPLOAD(P_LOAD_ID VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_RECALCULATION_ID VARCHAR;
    V_SOURCE_FILE VARCHAR;
    V_UPLOADED_BY VARCHAR;
    V_DATE_FROM DATE;
    V_DATE_TO DATE;
    V_RAW_ROWS NUMBER DEFAULT 0;
BEGIN
    SELECT MAX(SOURCE_FILE), MAX(UPLOADED_BY), MAX(DATA_PERIOD_START), MAX(DATA_PERIOD_END)
      INTO :V_SOURCE_FILE, :V_UPLOADED_BY, :V_DATE_FROM, :V_DATE_TO
      FROM CITORA.RAW.LOAD_HISTORY
     WHERE LOAD_ID = :P_LOAD_ID;

    IF (V_SOURCE_FILE IS NULL) THEN
        RETURN OBJECT_CONSTRUCT(
            'status', 'not_found',
            'load_id', P_LOAD_ID,
            'rows_deleted', 0
        );
    END IF;

    SELECT COUNT(*)
      INTO :V_RAW_ROWS
      FROM CITORA.RAW.CRM_DEALS
     WHERE "_LOAD_ID" = :P_LOAD_ID;

    SELECT UUID_STRING() INTO :V_RECALCULATION_ID;

    INSERT INTO CITORA.PLATFORM.RECALCULATION_QUEUE (
        RECALCULATION_ID, OPERATION_TYPE, LOAD_ID, REQUESTED_AT,
        REQUESTED_BY, DATE_FROM, DATE_TO, CONVERSION_PERIOD_DAYS, STATUS
    ) VALUES (
        :V_RECALCULATION_ID, 'DELETE', :P_LOAD_ID, CURRENT_TIMESTAMP(),
        COALESCE(:V_UPLOADED_BY, 'UNKNOWN'), :V_DATE_FROM, :V_DATE_TO, 30, 'PENDING'
    );

    INSERT INTO CITORA.PLATFORM.RECALCULATION_IDENTIFIERS (
        RECALCULATION_ID, PHONE_NUMBER_HASH, CONTACT_ID_HASH, CREATED_AT
    )
    SELECT DISTINCT :V_RECALCULATION_ID, NULLIF(TRIM("phone_number"), ''),
           NULLIF(TRIM("contact_id"), ''), CURRENT_TIMESTAMP()
      FROM CITORA.RAW.CRM_DEALS
     WHERE "_LOAD_ID" = :P_LOAD_ID
       AND (NULLIF(TRIM("phone_number"), '') IS NOT NULL
            OR NULLIF(TRIM("contact_id"), '') IS NOT NULL);

    DELETE FROM CITORA.RAW.CRM_DEALS
     WHERE "_LOAD_ID" = :P_LOAD_ID;

    DELETE FROM CITORA.RAW.LOAD_HISTORY
     WHERE LOAD_ID = :P_LOAD_ID;

    RETURN OBJECT_CONSTRUCT(
        'status', 'deleted',
        'load_id', P_LOAD_ID,
        'recalculation_id', V_RECALCULATION_ID,
        'date_from', V_DATE_FROM,
        'date_to', V_DATE_TO,
        'source_file', V_SOURCE_FILE,
        'rows_deleted', V_RAW_ROWS
    );
END;
$$;

GRANT USAGE ON PROCEDURE CITORA.PLATFORM.DELETE_UPLOAD(VARCHAR)
    TO ROLE CITORA_FRONTEND_UPLOADER;

DESCRIBE PROCEDURE CITORA.PLATFORM.DELETE_UPLOAD(VARCHAR);
