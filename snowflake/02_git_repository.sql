-- Connect the public GitHub repository to Snowflake.
-- Run after 01_infrastructure.sql with a role that can create API integrations.

USE ROLE ACCOUNTADMIN;

CREATE API INTEGRATION IF NOT EXISTS CITORA_GITHUB_API_INTEGRATION
    API_PROVIDER = git_https_api
    API_ALLOWED_PREFIXES = (
        'https://github.com/nbobrikov/Citora-AI-Analytics-'
    )
    ENABLED = TRUE
    COMMENT = 'Read-only public GitHub access for Citora AI Analytic';

GRANT USAGE ON INTEGRATION CITORA_GITHUB_API_INTEGRATION
    TO ROLE SYSADMIN;
GRANT USAGE ON INTEGRATION CITORA_GITHUB_API_INTEGRATION
    TO ROLE CITORA_LOADER;

USE ROLE SYSADMIN;
USE DATABASE CITORA;
USE SCHEMA PLATFORM;

CREATE GIT REPOSITORY IF NOT EXISTS CITORA.PLATFORM.CITORA_REPO
    ORIGIN = 'https://github.com/nbobrikov/Citora-AI-Analytics-.git'
    API_INTEGRATION = CITORA_GITHUB_API_INTEGRATION
    COMMENT = 'Snowflake clone of the Citora AI Analytic GitHub repository';

GRANT READ, WRITE ON GIT REPOSITORY CITORA.PLATFORM.CITORA_REPO
    TO ROLE CITORA_LOADER;

ALTER GIT REPOSITORY CITORA.PLATFORM.CITORA_REPO FETCH;

SHOW GIT BRANCHES IN CITORA.PLATFORM.CITORA_REPO;
LIST @CITORA.PLATFORM.CITORA_REPO/branches/main/;
